#!/usr/bin/env python3
# Writes the compiled compute shaders (SPIR-V files) into one C file: a table of their names (the file
# name without .spv), their words and their sizes, which vulkan/common.c looks shaders up in.
# Usage: embed_spirv.py OUTPUT.c INPUT.spv...
import os
import sys


def main():
    out, inputs = sys.argv[1], sorted(sys.argv[2:], key=os.path.basename)
    lines = ['/* generated by embed_spirv.py: do not edit */',
             '#include <stddef.h>', '#include <stdint.h>', '#include "vulkan/shaders.h"', '']
    names = []
    for i, path in enumerate(inputs):
        with open(path, 'rb') as f:
            data = f.read()
        if len(data) % 4:
            sys.exit('%s: not a SPIR-V file' % path)
        words = [int.from_bytes(data[k:k + 4], 'little') for k in range(0, len(data), 4)]
        name = os.path.basename(path)[:-len('.spv')] if path.endswith('.spv') else os.path.basename(path)
        names.append((name, i, len(data)))
        lines.append('static const uint32_t spv_%d[%d] = {' % (i, len(words)))
        for k in range(0, len(words), 8):
            lines.append('    ' + ', '.join('0x%08xu' % w for w in words[k:k + 8]) + ',')
        lines.append('};')
    lines.append('')
    lines.append('const VmafVulkanShader vmaf_vulkan_shaders[] = {')
    for name, i, size in names:
        lines.append('    { "%s", spv_%d, %d },' % (name, i, size))
    lines.append('    { NULL, NULL, 0 },')
    lines.append('};')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
